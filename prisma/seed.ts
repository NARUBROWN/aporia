type ColumnType = "text" | "number" | "date" | "boolean";
type SeedSheet = {
  id: string;
  name: string;
  columns: string[];
  columnTypes: ColumnType[];
  rowIds: string[];
  rows: string[][];
};

function sheet(
  id: string,
  name: string,
  columns: string[],
  columnTypes: ColumnType[],
  rows: string[][],
): SeedSheet {
  return {
    id,
    name,
    columns,
    columnTypes,
    rowIds: rows.map((_, index) => `${id}-row-${index + 1}`),
    rows,
  };
}


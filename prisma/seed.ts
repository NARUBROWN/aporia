function relation(
  id: string,
  sourceSheetId: string,
  sourceColumn: string,
  targetSheetId: string,
  targetColumn: string,
  relationType: "1:1" | "1:N" | "N:1" | "N:N",
) {
  const source = sheets.find((item) => item.id === sourceSheetId)!;
  const target = sheets.find((item) => item.id === targetSheetId)!;
  const sourceIndex = source.columns.indexOf(sourceColumn);
  const targetIndex = target.columns.indexOf(targetColumn);
  const links = source.rows.flatMap((sourceRow, sourceRowIndex) =>
    target.rows.flatMap((targetRow, targetRowIndex) =>
      sourceRow[sourceIndex] &&
      sourceRow[sourceIndex] === targetRow[targetIndex] &&
      (sourceSheetId !== targetSheetId || sourceRowIndex !== targetRowIndex)
        ? [
            {
              sourceRowId: source.rowIds[sourceRowIndex],
              targetRowId: target.rowIds[targetRowIndex],
            },
          ]
        : [],
    ),
  );
  return {
    id,
    sourceSheetId,
    sourceColumn,
    targetSheetId,
    targetColumn,
    relationType,
    updateOption: "none",
    links,
  };
}

